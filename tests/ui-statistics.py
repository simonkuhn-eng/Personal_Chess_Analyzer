"""Focused statistics UI, real App and components with isolated local data."""
from pathlib import Path
import re
from playwright.sync_api import sync_playwright

out = Path(__file__).resolve().parents[1] / 'tmp' / 'statistics-ui'
out.mkdir(parents=True, exist_ok=True)
html = '''<!doctype html><html><head><meta charset="utf-8"></head><body><div id="root"></div><script type="module">
import RefreshRuntime from '/@react-refresh';RefreshRuntime.injectIntoGlobalHook(window);window.$RefreshReg$=()=>{};window.$RefreshSig$=()=>(type)=>type;window.__vite_plugin_react_preamble_installed__=true;
</script><script type="module" src="/tests/ui-statistics-fixture.jsx"></script></body></html>'''
checks, errors = [], []
def ok(name, condition):
    assert condition, name
    checks.append(name)
    print('OK', name, flush=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=r'C:\Program Files\Google\Chrome\Application\chrome.exe', headless=True)
    page = browser.new_page(viewport={'width': 1500, 'height': 920})
    page.set_default_timeout(12000)
    page.on('pageerror', lambda err: errors.append(str(err)))
    page.route('**/__statistics__', lambda route: route.fulfill(status=200, content_type='text/html', body=html))
    page.goto('http://127.0.0.1:5173/__statistics__')
    page.locator('.review-layout').wait_for()
    ok('Statistics remain lazy at startup', page.evaluate('window.__statistics.requests.length') == 0)
    page.get_by_role('button', name='Fehler-Diagnostik', exact=True).click()
    overview = page.get_by_role('region', name='Leistung nach Bedenkzeit')
    overview.wait_for()
    rapid = overview.locator('[data-performance-row="chesscom:alice:rapid"]')
    ok('Known platforms and time controls stay separate', overview.locator('[data-performance-row]').count() == 5)
    ok('Own rating and rating change shown', '1041' in rapid.inner_text() and '+61 im Zeitraum' in rapid.inner_text())
    ok('No duplicate old time-control table', page.get_by_text('Leistung nach Zeitkontrolle', exact=True).count() == 0)
    rapid.get_by_role('button', name='Details Schnellschach Chess.com Alice').click()
    chart = overview.get_by_role('img', name='Ratingverlauf Chess.com Schnellschach Alice')
    chart.wait_for()
    ok('Expandable rating history has three real observations', chart.locator('a').count() == 3)
    ok('Missing endgame phase is blank', overview.locator('.statistics-phases > div').last.locator('strong').inner_text() == '—')
    page.screenshot(path=str(out / 'statistics-expanded.png'))
    for width, height in [(1500, 920), (1100, 700)]:
        page.set_viewport_size({'width': width, 'height': height})
        bounds = page.get_by_role('region', name='Statistikfilter').bounding_box()
        ok(f'Filters and page fit {width}', bounds['x'] >= 0 and bounds['x'] + bounds['width'] <= width and page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
    page.set_viewport_size({'width': 1500, 'height': 920})
    chart.locator('a').last.click()
    page.locator('.review-layout').wait_for()
    ok('Rating observation opens source game', page.evaluate('window.__statistics.gameRequests.at(-1)') == 'rapid-last')
    page.get_by_role('button', name='Fehler-Diagnostik', exact=True).click()
    overview.wait_for()
    page.get_by_label('Statistikzeitraum', exact=True).select_option('30')
    page.get_by_label('Statistikplattform', exact=True).select_option('chesscom')
    page.get_by_label('Statistikbedenkzeit', exact=True).select_option('rapid')
    page.wait_for_function('window.__statistics.requests.at(-1).filter.days===30 && window.__statistics.requests.at(-1).filter.platform==="chesscom" && window.__statistics.requests.at(-1).filter.timeControl==="rapid"')
    page.wait_for_function('document.querySelectorAll("[data-performance-row]").length===1')
    ok('All filters reach backend together', '+41 im Zeitraum' in rapid.inner_text())
    phase = page.get_by_role('region', name='Eröffnungsqualität')
    ok('Opening diagnosis uses same scope', '2 Fehler im Zugfenster' in phase.inner_text())
    overview.locator('.statistics-highlights summary').click()
    overview.locator('.statistics-example-list button').click()
    page.locator('.review-layout').wait_for()
    ok('Brilliant example opens source game', page.evaluate('window.__statistics.gameRequests.at(-1)') == 'rapid-last')
    page.get_by_role('button', name='Fehler-Diagnostik', exact=True).click()
    overview.wait_for()
    page.get_by_label('Statistikzeitraum', exact=True).select_option('7')
    page.wait_for_function('window.__statistics.requests.at(-1).filter.days===7')
    phase.wait_for()
    phase.get_by_role('button', name='Eröffnungsfehler ansehen').click()
    page.locator('.training-deck-board-column .board-container').wait_for()
    ok('Training carries period/platform/speed filter', 'Letzte 7 Tage · Chess.com · Schnellschach' in page.locator('.training-deck-diagnostic-filter').inner_text())
    ok('Only one current early card is trained', '0/1 gemeistert' in page.locator('.training-deck-view').inner_text())
    page.get_by_role('button', name='Fehler-Diagnostik', exact=True).click()
    overview.wait_for()
    page.get_by_label('Statistikplattform', exact=True).select_option('lichess')
    overview.locator('[data-performance-row="lichess:alice:rapid"]').wait_for()
    ok('Lichess rating pool never mixed with Chess.com', '1850' in overview.inner_text() and '1041' not in overview.inner_text())
    page.get_by_label('Statistikbedenkzeit', exact=True).select_option('bullet')
    page.get_by_text('Keine eigenen Partien für diese Auswahl.', exact=False).wait_for()
    ok('Empty filtered result keeps filters usable', page.get_by_label('Statistikzeitraum', exact=True).is_enabled())
    page.get_by_label('Statistikplattform', exact=True).select_option('chesscom')
    page.get_by_label('Statistikbedenkzeit', exact=True).select_option('daily')
    overview.locator('[data-performance-row="chesscom:alice:daily"]').wait_for()
    daily = overview.locator('[data-performance-row="chesscom:alice:daily"]')
    ok('Partial game still has result/rating but no fake accuracy', '773' in daily.inner_text() and daily.locator('td').nth(3).locator('strong').inner_text() == '—')
    ok('Partial-only filter does not pretend zero analysis errors', daily.locator('td').nth(4).locator('strong').inner_text() == '—')
    ok('No uncaught UI exceptions', not errors)
    browser.close()
print(f'{len(checks)} statistics UI checks passed.')
